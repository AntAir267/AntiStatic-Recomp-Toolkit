"""Check a tree (the public export) for anything that must not be published.

    audit_public.py <tree> [--history]

AntiStatic publishes only hand-written code. This fails (exit 1) if the tree holds:
  game programs      files that start like a Windows program (MZ) or a disc image, whatever
                     their name, and the usual program/disc/archive extensions
  generated C        what translator/recomp.py writes says so in its first line ("Generated from
                     the user's game files", "Generated by tools/recomp.py"); generated C is
                     the game's code in another form and is never shared
  game assets        the usual sound/movie/texture/archive extensions
  private paths      home folders, the private repo's names, session ids
  private names      a port that stays private (its name in any case, its environment variable
                     prefix) and the maintainer's first name as a word in prose (case-sensitive,
                     so AntiStatic, AntAir267, "ant" and Unlicense pass); text files only. The
                     patterns are written with escapes so this file passes its own check.
and it lists for a look (exit 0): images outside art/, and any file over 2 MB.
With --history it also checks every file in every commit of the tree's own git history, since
a public repository shows all of it (deleting a file later doesn't unpublish it).

The idea, and the reminder about history, come from pcrecomp's tools/audit_repo.py (sp00nznet,
MIT). This file is AntiStatic's own (Unlicense).
"""
import os, re, subprocess, sys

PROGRAM_EXT = {'.exe', '.dll', '.ocx', '.drv', '.sys', '.com', '.iso', '.bin', '.cue', '.img', '.mdf',
               '.nrg', '.cab', '.xbe', '.xex', '.elf'}
ASSET_EXT = {'.bik', '.smk', '.wav', '.mp3', '.ogg', '.wma', '.avi', '.mpg', '.xmv', '.pak', '.wad',
             '.res', '.dat', '.tga', '.dds', '.bmp', '.pcx', '.mid', '.xmi', '.sgt', '.dls', '.zip',
             '.upk', '.u', '.utx', '.bod', '.bob'}
IMAGE_EXT = {'.png', '.jpg', '.jpeg', '.gif', '.webp'}
GEN_MARKERS = (b"Generated from the user's game files", b'Generated by tools/recomp.py',
               b'Generated by translator/recomp.py')
PRIVATE = re.compile(rb'/home/[a-z]|DevWork|-internal\b|local_[0-9a-f]{8}-|antair(?!do|267)', re.I)
PRIVATE_PORT = re.compile(rb'b\x61llistics|\bB\x41L_', re.I)
PRIVATE_NAME = re.compile(rb'\bA\x6et\b')    # the name alone, before 's or a colon too; case-sensitive
SELF = ('audit_public.py', 'export_public.sh')
BIG = 2 << 20


def check(name, data):
    """(problems, notes) for one file"""
    bad, look = [], []
    ext = os.path.splitext(name)[1].lower()
    if ext in PROGRAM_EXT or data[:2] == b'MZ' or data[0x8001:0x8006] == b'CD001':
        bad.append('a program or disc image')
    if ext in ASSET_EXT:
        bad.append('a game asset type (%s)' % ext)
    if any(m in data[:400] for m in GEN_MARKERS):
        bad.append('generated C')
    if PRIVATE.search(data) and not name.endswith(SELF):
        bad.append('a private path or name')
    if b'\0' not in data[:8192]:
        m = PRIVATE_PORT.search(data)
        if m:
            bad.append('a private port named (%r, line %d)' % (m.group().decode(), data.count(b'\n', 0, m.start()) + 1))
        m = PRIVATE_NAME.search(data)
        if m:
            bad.append("the maintainer's first name (line %d)" % (data.count(b'\n', 0, m.start()) + 1))
    if ext in IMAGE_EXT and not name.startswith('art/'):
        look.append('an image outside art/: is it ours?')
    if len(data) > BIG:
        look.append('%.1f MB' % (len(data) / 1048576))
    return bad, look


def audit_tree(root):
    bad = look = 0
    for dirpath, dirs, files in os.walk(root):
        dirs[:] = [d for d in dirs if d != '.git']
        for f in files:
            p = os.path.join(dirpath, f)
            rel = os.path.relpath(p, root)
            b, l = check(rel, open(p, 'rb').read())
            for x in b:
                print('NOT PUBLISHABLE  %s: %s' % (rel, x)); bad += 1
            for x in l:
                print('look             %s: %s' % (rel, x)); look += 1
    return bad, look


def audit_history(root):
    bad = 0
    try:
        revs = subprocess.run(['git', '-C', root, 'rev-list', '--all'], capture_output=True, text=True,
                              check=True).stdout.split()
    except (subprocess.CalledProcessError, FileNotFoundError):
        return 0
    seen = set()
    for rev in revs:
        ls = subprocess.run(['git', '-C', root, 'ls-tree', '-r', rev], capture_output=True, text=True).stdout
        for line in ls.splitlines():
            meta, path = line.split('\t', 1)
            blob = meta.split()[2]
            if blob in seen:
                continue
            seen.add(blob)
            data = subprocess.run(['git', '-C', root, 'cat-file', 'blob', blob], capture_output=True).stdout
            for x in check(path, data)[0]:
                print('NOT PUBLISHABLE  %s (in commit %s): %s' % (path, rev[:10], x)); bad += 1
    return bad


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    root = sys.argv[1]
    bad, look = audit_tree(root)
    if '--history' in sys.argv[2:]:
        bad += audit_history(root)
    print('%d problems, %d to look at' % (bad, look))
    sys.exit(1 if bad else 0)


if __name__ == '__main__':
    main()
