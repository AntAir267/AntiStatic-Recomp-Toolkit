#!/usr/bin/env python3
"""A port's pipeline list (e.g. data/vk_pipelines.txt: the pipelines its test routes make, keys and vertex declarations
in hex, no game code; made by tools/vk9/vk_plist.py) as a C string for runtime/vk9/vk_d3d9.c's built-in list: the
port puts the output, named vk_plist.h, on its include path. Usage: tools/vk9/plist2h.py IN OUT"""
import sys

lines = [l.strip() for l in open(sys.argv[1]) if l.strip() and not l.startswith('#')]
with open(sys.argv[2], 'w') as o:
    o.write('/* generated by tools/vk9/plist2h.py from %s: %d pipelines */\n' % (sys.argv[1], max(len(lines) - 1, 0)))
    o.write('static const char vk_plist_text[] =\n')
    if not lines:
        o.write('    "";\n')
    for i, l in enumerate(lines):
        o.write('    "%s\\n"%s\n' % (l, ';' if i == len(lines) - 1 else ''))
