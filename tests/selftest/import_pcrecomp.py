"""Turns pcrecomp's lifter test cases (tools/lift/difftest.py, MIT: LICENSE.pcrecomp) into
AntiStatic self-test cases: tests/selftest/pcrecomp_cases.s (each case's code bytes as a function)
and pcrecomp_cases.json (its fixed start state and the flags to compare). run.py runs them once
each, from that state, in Unicorn and translated, like our own cases.

    python3 tests/selftest/import_pcrecomp.py PCRECOMP_CHECKOUT

Their window is mapped onto ours: their scratch page (base + 0x10000) is our scratch at
0x10000000, so registers and memory pointing into it move with it. A case is left out (and
listed, with why) when it points anywhere else, sets esp, or jumps outside its own code.
Each function saves esp (put back before its ret: a case may leave the stack unbalanced), sets
their FPU control word (precision double), runs the code and stores EFLAGS (DF compared too;
flags their case calls undefined are not).
Needs capstone and unicorn (their file imports unicorn's constants).
"""
import json, os, re, struct, sys

from capstone import Cs, CS_ARCH_X86, CS_MODE_32, CS_OP_IMM, CS_OP_MEM

HERE = os.path.dirname(os.path.abspath(__file__))
src_dir = sys.argv[1]
src = open(os.path.join(src_dir, 'tools', 'lift', 'difftest.py')).read()
commit = os.popen('git -C "%s" rev-parse --short HEAD' % src_dir).read().strip()
# the case list only: the module up to its runner, without the lifter import
body = src[:src.index('\ndef run_unicorn(')]
body = body.replace('from tools.lift.lift32 import Lifter', '')
import types
mod = types.ModuleType('pcrecomp_difftest')
mod.__file__ = os.path.join(src_dir, 'tools', 'lift', 'difftest.py')
sys.modules[mod.__name__] = mod
ns = mod.__dict__
exec(compile(body, mod.__file__, 'exec'), ns)
T_BASE, T_SCRATCH, T_STACK = ns['BASE'], ns['SCRATCH'], ns['STACK']
T_SIZE = ns['SIZE']
SCRATCH, PAGE = 0x10000000, 0x1000
RESULTS = 0xf00
SAVED_ESP = 0xffc         # esp at entry, put back before ret (a case may leave the stack unbalanced)
FLAG_BITS = {'CF': 0x1, 'PF': 0x4, 'AF': 0x10, 'ZF': 0x40, 'SF': 0x80, 'DF': 0x400, 'OF': 0x800}

# where Unicorn, the reference, is the one that differs from a real x86 (the translation runs the
# real x87): reported, not counted as failures. Checked by hand against Intel's manual.
EMULATOR_GAPS = {
    'fsin.c2': 'Unicorn leaves C1 clear after fsin; a real x87 sets it when the result was rounded up '
               '(Intel SDM, FSIN: C1 "set if result was rounded up")',
}

md = Cs(CS_ARCH_X86, CS_MODE_32)
md.detail = True


def in_window(v):
    return T_BASE <= v < T_BASE + T_SIZE


def why_not(case):
    regs = case.start_regs()
    if case.regs.get('esp') not in (None, T_STACK):
        return 'sets esp'
    for r, v in regs.items():
        if r != 'esp' and in_window(v) and not T_SCRATCH <= v < T_SCRATCH + RESULTS:
            return '%s points outside the scratch page' % r
    for va, data in case.mem.items():
        if not T_SCRATCH <= va or va + len(data) > T_SCRATCH + RESULTS:
            return 'memory outside the scratch page (%x)' % va
    end = 0
    for i in md.disasm(bytes(case.code), 0):
        end = i.address + i.size
        for op in i.operands:
            if op.type == CS_OP_MEM and in_window(op.mem.disp & 0xffffffff):
                return 'an absolute address'
            if op.type == CS_OP_IMM and in_window(op.imm & 0xffffffff) and i.group(1) is False:
                return 'an absolute address'
        if i.group(1) or i.group(7):            # jump, relative branch
            for op in i.operands:
                if op.type == CS_OP_IMM and not 0 <= op.imm <= len(case.code):
                    return 'a jump outside its code'
        if i.mnemonic in ('ret', 'call', 'int', 'int3', 'hlt', 'iretd'):
            return 'a %s' % i.mnemonic
    if end != len(case.code):
        return 'code that does not disassemble whole'
    return None


asm = ['# Generated by tests/selftest/import_pcrecomp.py from pcrecomp %s tools/lift/difftest.py' % commit,
       '# (MIT, Copyright (c) 2026 sp00nz: tools/coverage/LICENSE.pcrecomp). Each case: their FPU',
       '# control word, their code bytes, EFLAGS stored to the first result slot, ret.',
       '        .intel_syntax noprefix', '        .text',
       'pc_fpu_cw:', '        .word 0x%04x' % ns['FPU_CONTROL_WORD'], '        .p2align 4']
meta, skipped, names = {}, [], set()
for case in ns['CASES']:
    why = why_not(case)
    if why:
        skipped.append((case.name, why))
        continue
    name = 'case_pc_' + re.sub(r'[^a-zA-Z0-9]', '_', case.name)
    while name in names:
        name += '_'
    names.add(name)
    asm += ['%s:' % name,
            '        mov dword ptr [0x%x], esp' % (SCRATCH + SAVED_ESP),
            '        fldcw word ptr [pc_fpu_cw]',
            '        .byte ' + ', '.join('0x%02x' % b for b in case.code),
            '        mov esp, dword ptr [0x%x]' % (SCRATCH + SAVED_ESP),     # (mov: flags kept)
            '        pushfd',
            '        pop dword ptr [0x%x]' % (SCRATCH + RESULTS),
            '        mov dword ptr [esp - 4], 0',
            '        ret', '        .p2align 4']
    regs = {}
    for r, v in case.start_regs().items():
        if r == 'esp':
            continue
        regs[r] = (v - T_SCRATCH + SCRATCH) if T_SCRATCH <= v < T_SCRATCH + PAGE else v
    mem = {'%x' % (va - T_SCRATCH): bytes(data).hex() for va, data in case.mem.items()}
    mask = 0x8d5 | 0x400
    for f in case.undef:
        mask &= ~FLAG_BITS[f]
    meta[name] = dict(source=case.name, regs=regs, mem=mem, mask=mask, known=case.known or None,
                      emulator_gap=EMULATOR_GAPS.get(case.name))
open(os.path.join(HERE, 'pcrecomp_cases.s'), 'w').write('\n'.join(asm) + '\n')
json.dump(dict(commit=commit, cases=meta, skipped=dict(skipped)),
          open(os.path.join(HERE, 'pcrecomp_cases.json'), 'w'), indent=1, sort_keys=True)
print('%d cases, %d left out:' % (len(meta), len(skipped)))
for n, w in skipped:
    print('  %-40s %s' % (n, w))
